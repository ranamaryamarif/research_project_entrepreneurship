def status(skewness):
  results = {}
  for col, skew in skewness.items():
    if skew > 1:
      category = "High Positive / Right Skew"

    elif skew < -1:
      category = "High Negative / Left Skew"

    elif -0.5 <= skew <= 0.5:
      category = "Approximately Normal"

    else:
      category = "Moderate Skew"

    results[col] = {"skewness": skew, "category": category}

  return pd.DataFrame(results).T

