def plot_loss_curve(train_losses, valid_losses, train_accuracies, valid_accuracies):
  plt.figure(figsize=(10, 5))
  plt.plot(train_losses, label="Train Loss", marker='o')
  plt.plot(valid_losses, label="Validation Loss", marker='o')
  plt.xlabel("Iterations")
  plt.ylabel("Loss")
  plt.title("Loss Curve")
  plt.legend()
  plt.show()

  # Plot Accuracy Curve
  plt.figure(figsize=(10, 5))
  plt.plot(train_accuracies, label="Train Accuracy", marker='o')
  plt.plot(valid_accuracies, label="Validation Accuracy", marker='o')
  plt.xlabel("Iterations")
  plt.ylabel("Accuracy")
  plt.title("Accuracy Curve")
  plt.legend()
  plt.show()

def confusion_matrix_plot(best_model, X_test, Y_test):
  y_pred_test = best_model.predict(X_test)

  from sklearn.metrics import classification_report, confusion_matrix

  cm = confusion_matrix(Y_test, y_pred_test)

  plt.figure(figsize=(8, 6))
  sns.heatmap(cm, annot=True, fmt = 'd', cmap = 'Blues')
  plt.xlabel('Predicted Labels')
  plt.ylabel('True Labels')
  plt.title('Confusion Matrix')
  plt.show()

  print(accuracy_score(Y_test, y_pred_test))
  print(classification_report(Y_test, y_pred_test))

  return y_pred_test

def auc_curve(Y_test, y_pred_test):
  fpr, tpr, thresholds = roc_curve(Y_test, y_pred_test)
  auc = roc_auc_score(Y_test, y_pred_test)

  plt.figure(figsize=(8, 6))
  plt.plot(fpr, tpr, label=f'AUC = {auc:.2f}')
  plt.plot([0, 1], [0, 1], 'k--')
  plt.legend()
  plt.xlabel('False Positive Rate')
  plt.ylabel('True Positive Rate')
  plt.title('ROC Curve')
  plt.show()

